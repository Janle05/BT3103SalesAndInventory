        private void btnAdd_Click(object sender, EventArgs e)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(textBox1.Text))
                {
                    MessageBox.Show(
                        "Product name is required.",
                        "Validation",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    textBox1.Focus();
                    return;
                }

                if (comboBox1.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a category.",
                        "Validation",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    comboBox1.Focus();
                    return;
                }

                if (comboBox3.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a supplier.",
                        "Validation",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    comboBox3.Focus();
                    return;
                }

                Product product = new Product
                {
                    ProductName = textBox1.Text.Trim(),
                    CategoryID = Convert.ToInt32(comboBox1.SelectedValue),
                    SupplierID = Convert.ToInt32(comboBox3.SelectedValue),
                    UnitPrice = numericUpDown1.Value,
                    InitialStock = Convert.ToInt32(numericUpDown2.Value),
                    ReorderLevel = Convert.ToInt32(numericUpDown3.Value),
                    Status = comboBox2.Text
                };

                productService.AddProduct(product);

                MessageBox.Show(
                    "Product added successfully!",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information);

                LoadProducts();
                ClearFields();
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Error adding product:\n" + ex.Message,
                    "Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
        }

        private void btnUpdate_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedProductID == 0)
                {
                    MessageBox.Show(
                        "Please select a product from the table first.",
                        "Update Product",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    return;
                }

                if (string.IsNullOrWhiteSpace(textBox1.Text))
                {
                    MessageBox.Show(
                        "Product name is required.",
                        "Validation",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    textBox1.Focus();
                    return;
                }

                if (comboBox1.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a category.",
                        "Validation",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    return;
                }

                if (comboBox3.SelectedIndex == -1)
                {
                    MessageBox.Show(
                        "Please select a supplier.",
                        "Validation",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    return;
                }

                Product product = new Product
                {
                    ProductID = selectedProductID,
                    ProductName = textBox1.Text.Trim(),
                    CategoryID = Convert.ToInt32(comboBox1.SelectedValue),
                    SupplierID = Convert.ToInt32(comboBox3.SelectedValue),
                    UnitPrice = numericUpDown1.Value,
                    InitialStock = Convert.ToInt32(numericUpDown2.Value),
                    ReorderLevel = Convert.ToInt32(numericUpDown3.Value),
                    Status = comboBox2.Text
                };

                productService.UpdateProduct(product);

                MessageBox.Show(
                    "Product updated successfully!",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information);

