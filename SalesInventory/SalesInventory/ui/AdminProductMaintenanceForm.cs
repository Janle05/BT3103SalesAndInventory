                ClearFields();
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Error updating product:\n" + ex.Message,
                    "Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
        }

        private void btnDelete_Click(object sender, EventArgs e)
        {
            try
            {
                if (selectedProductID == 0)
                {
                    MessageBox.Show(
                        "Please select a product first.",
                        "Deactivate Product",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);

                    return;
                }

                DialogResult result = MessageBox.Show(
                    "Are you sure you want to deactivate this product?",
                    "Confirm Deactivation",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question);

                if (result != DialogResult.Yes)
                    return;

                productService.DeactivateProduct(selectedProductID);

                MessageBox.Show(
                    "Product deactivated successfully!",
                    "Success",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information);

                LoadProducts();
                ClearFields();
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Error deactivating product:\n" + ex.Message,
                    "Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
        }

        private void button11_Click(object sender, EventArgs e)
        {
            try
            {
                string keyword = txtSearchProduct.Text.Trim();

                if (string.IsNullOrWhiteSpace(keyword))
                {
                    LoadProducts();
                    return;
                }

                var results = productService.SearchProducts(keyword);

                dgvProducts.DataSource = null;
                dgvProducts.DataSource = results;

                if (results.Count == 0)
                {
                    MessageBox.Show(
                        "No product found.",
                        "Search",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Information);
                }

                dgvProducts.ClearSelection();
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Error searching products:\n" + ex.Message,
                    "Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
        }

        private void dataGridView1_CellContentClick(object sender, DataGridViewCellEventArgs e)
        {
            try
            {
                if (e.RowIndex < 0)
                    return;

                DataGridViewRow row = dgvProducts.Rows[e.RowIndex];

                if (row.Cells["ProductID"].Value == null)
                    return;

                selectedProductID =
                    Convert.ToInt32(row.Cells["ProductID"].Value);

                textBox2.Text = selectedProductID.ToString();

                textBox1.Text =
                    row.Cells["ProductName"].Value?.ToString() ?? "";

                numericUpDown1.Value =
                    Convert.ToDecimal(row.Cells["UnitPrice"].Value);

                numericUpDown2.Value =
                    Convert.ToDecimal(row.Cells["InitialStock"].Value);

                numericUpDown3.Value =
                    Convert.ToDecimal(row.Cells["ReorderLevel"].Value);

                string status =
                    row.Cells["Status"].Value?.ToString() ?? "Active";

                if (comboBox2.Items.Contains(status))
                    comboBox2.SelectedItem = status;

                // Select Category
                if (row.Cells["CategoryID"].Value != null)
                {
                    int categoryID =
                        Convert.ToInt32(row.Cells["CategoryID"].Value);

                    comboBox1.SelectedValue = categoryID;
                }

                // Select Supplier
                if (row.Cells["SupplierID"].Value != null)
                {
                    int supplierID =
                        Convert.ToInt32(row.Cells["SupplierID"].Value);

                    comboBox3.SelectedValue = supplierID;
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Error selecting product:\n" + ex.Message,
                    "Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
        }

